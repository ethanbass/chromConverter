  skip_if_not_installed("chromConverterExtraTests")

  path <- system.file("STRD15.SMS", package = "chromConverterExtraTests")
  skip_if_not(file.exists(path))

  # this used to fail outright: the scan column was subset with `MS1[, 1]`,
  # which returns a one-column `data.table` and so was read as a join key
  # rather than as row indices. The TIC and BPC intensity column also came out
