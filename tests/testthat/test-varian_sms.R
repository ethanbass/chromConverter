test_that("acquisition timestamps are read correctly", {
  skip_on_cran()
  skip_if_not_installed("chromConverterExtraTests")

  path <- system.file("STRD15.SMS", package = "chromConverterExtraTests")
  skip_if_not(file.exists(path))
  f <- file(path, "rb")
  on.exit(close(f), add = TRUE)
  meta <- read_varian_msdata_header(f)

  # matches the startTimeStamp OpenChrom writes for this sample
  # ("2014-08-08T23:50:55.000-04:00")
  expect_equal(meta$acquisition_start,
               as.POSIXct("2014-08-09 03:50:55", tz = "UTC"))
  expect_equal(meta$acquisition_end,
               as.POSIXct("2014-08-09 04:20:54", tz = "UTC"))

  # the interval between them is the span of the chromatogram
  chroms <- read_varian_chromatograms(f, n_time = meta$n_scan,
                                      format_out = "matrix",
                                      data_format = "long")
  span <- difftime(meta$acquisition_end, meta$acquisition_start, units = "mins")
  expect_equal(as.numeric(span), max(chroms[, "rt"]) - min(chroms[, "rt"]),
               tolerance = 0.001)
})

