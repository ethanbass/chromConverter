test_that("MS stream is bounded by the MSData section, not the file", {
  skip_on_cran()
  skip_if_not_installed("chromConverterExtraTests")

  # DCM1.SMS carries ~2 MB of peak tables and results after the spectra, so the
  # bound matters there; STRD15.SMS ends just past MSData and should be a no-op.
  path <- system.file("DCM1.SMS", package = "chromConverterExtraTests")
  skip_if_not(file.exists(path))
  f <- file(path, "rb")
  on.exit(close(f), add = TRUE)
  offsets <- read_varian_offsets(f)
  ms_end <- offsets$end[offsets$name == "MSData"]

  expect_lt(ms_end, file.size(path))

  # reading to the section end and to EOF must agree
  seek_to_spectra <- function(f){
    meta <- read_varian_msdata_header(f)
    chroms <- read_varian_chromatograms(f, n_time = meta$n_scan,
                                        format_out = "matrix",
                                        data_format = "long")
    skip_null_bytes(f)
    nrow(chroms) - max(which(chroms[, "tic"] == 0))
  }
  n_scans <- seek_to_spectra(f)
  bounded <- read_varian_ms_stream(f, n_scans = n_scans, flen = ms_end)
  seek(f, 0)
  n_scans <- seek_to_spectra(f)
  unbounded <- read_varian_ms_stream(f, n_scans = n_scans,
                                     flen = file.size(path))

  expect_equal(bounded, unbounded)
})

