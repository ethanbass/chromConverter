  expect_equal(attr(x3$MS1, "detector"), "MS")
  expect_equal(attr(x3$MS1, "sample_name"), "STRD15")
})

# Synthetic checks for the 'Varian SMS' variable-length integer encoding.
# These need no external file, so they cover the branches that the sample files
# in `chromConverterExtraTests` do not exercise: within the MS regions of
# `STRD15.SMS` and `DCM1.SMS` the leading nibble never exceeds `C`, leaving the
# 27/28-bit rules for `d` = D, E and F untested by real data.

# Encode `value` as a token with leading nibble `d`, big-endian, with the low
# bits carried in the trailing bytes. For d < 4 the token is a single byte and
# the nibble is part of the value itself, so `d` must be the value's high
# nibble.
sms_token <- function(d, value){
  len <- 1L + d %/% 4L
  if (len == 1L){
    stopifnot(value %/% 16L == d)
    return(as.raw(value))
  }
  bytes <- integer(len)
  for (i in seq_len(len - 1L)){
    bytes[len - i + 1L] <- bitwAnd(bitwShiftR(value, 8L * (i - 1L)), 0xFFL)
  }
  bytes[1] <- bitwOr(bitwShiftL(d, 4L),
                     bitwShiftR(value, 8L * (len - 1L)))
  as.raw(bytes)
}

test_that("MS stream decoder handles every token length class", {
  # one (m/z delta, intensity) pair per length class, then the scan terminator
  pairs <- list(c(d = 2, v = 0x25),        # 1 byte,  full byte
                c(d = 5, v = 0x1234),      # 2 bytes, low 13 bits
                c(d = 9, v = 0x1ABCDE),    # 3 bytes, low 21 bits
                c(d = 12, v = 0x5ABCDEF),  # 4 bytes, low 27 bits
                c(d = 15, v = 0xFABCDEF))  # 4 bytes, low 28 bits
  raw_stream <- c(unlist(lapply(pairs, function(p)
    c(sms_token(p[["d"]], p[["v"]]), sms_token(1L, 0x11)))),
    as.raw(c(0, 0)))

  path <- tempfile()
  on.exit(unlink(path), add = TRUE)
  writeBin(raw_stream, path)
  f <- file(path, "rb")
  on.exit(close(f), add = TRUE)

  # `d` = 12 and 15 assemble to 3.3e9 and 4.3e9, past `.Machine$integer.max`,
  # so these also cover the 4-byte overflow path: the lead byte has to be masked
  # before the token is assembled, or the value comes back `NA`.
  expect_no_warning(
    x <- read_varian_ms_stream(f, n_scans = 1, flen = file.size(path),
                               format_out = "data.frame")
  )

  expect_equal(nrow(x), length(pairs))
  expect_true(all(x$scan == 1))
  # m/z is delta-encoded, so the column is the running sum of the deltas / 10
  expect_equal(x$mz, cumsum(vapply(pairs, `[[`, numeric(1), "v")) / 10)
  expect_equal(x$intensity, rep(0x11, length(pairs)))
  expect_false(anyNA(x))
})

