  expect_equal(unlist(x$MS1[1, ]), c(rt = 6.483867, mz = 60, intensity = 1),
               tolerance = 1e-6)
  expect_equal(dim(x$TIC), c(3432L, 2L))
})

test_that("read_null_terminated rejects non-text bytes", {
  b <- as.raw(c(0x41, 0x42, 0x00, 0xFF, 0xFE, 0x00))
  expect_equal(read_null_terminated(b, 0), "AB")
  expect_null(read_null_terminated(b, 3))   # not printable
  expect_null(read_null_terminated(b, 2))   # empty
  expect_null(read_null_terminated(b, 99))  # past the end
})
